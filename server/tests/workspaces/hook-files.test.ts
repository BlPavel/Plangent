import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createTestRepository } from '../support/git';

/** A worktree only gets tracked files, but hooks kept in the project may need files a tool generated and git ignores. */
test('a workspace receives the ignored files of the hooks folder, not the tracked hook scripts', async t => {
  const { copyHookSupportFiles } = await import('../../core-services').then(() => import('../../core/workspaces/prepare'));
  const { root, git, dispose } = createTestRepository();
  const workspace = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'plangent-hook-files-')), 'work');
  t.after(() => { try { git('worktree', 'remove', '--force', workspace); } catch { /* already gone */ } dispose(); fs.rmSync(path.dirname(workspace), { recursive: true, force: true }); });
  fs.mkdirSync(path.join(root, '.hooks', '_'), { recursive: true });
  fs.writeFileSync(path.join(root, '.hooks', 'pre-commit'), '#!/bin/sh\n. "$(dirname "$0")/_/helper.sh"\n');
  fs.writeFileSync(path.join(root, '.hooks', '_', '.gitignore'), '*\n');
  fs.writeFileSync(path.join(root, '.hooks', '_', 'helper.sh'), 'generated by the hook tool\n');
  fs.writeFileSync(path.join(root, 'code.txt'), 'code');
  git('config', 'core.hooksPath', '.hooks');
  git('add', '.'); git('-c', 'core.hooksPath=', 'commit', '-m', 'Fixture');
  git('worktree', 'add', '--detach', workspace, 'HEAD');
  assert.equal(fs.existsSync(path.join(workspace, '.hooks', 'pre-commit')), true, 'the tracked hook is in the worktree');
  assert.equal(fs.existsSync(path.join(workspace, '.hooks', '_', 'helper.sh')), false, 'the generated file is not');

  const log: string[] = [];
  fs.writeFileSync(path.join(workspace, '.hooks', 'pre-commit'), 'the branch version of the hook\n');
  await copyHookSupportFiles(root, workspace, text => log.push(text));
  assert.equal(fs.readFileSync(path.join(workspace, '.hooks', '_', 'helper.sh'), 'utf8'), 'generated by the hook tool\n');
  assert.equal(fs.readFileSync(path.join(workspace, '.hooks', 'pre-commit'), 'utf8'), 'the branch version of the hook\n', 'tracked scripts stay as the branch has them');
  assert.ok(log.some(line => line.includes('.hooks/_/helper.sh')));

  // Without a hooks folder inside the project nothing is copied.
  git('config', '--unset', 'core.hooksPath');
  fs.rmSync(path.join(workspace, '.hooks', '_'), { recursive: true, force: true });
  await copyHookSupportFiles(root, workspace, () => {});
  assert.equal(fs.existsSync(path.join(workspace, '.hooks', '_')), false);
  git('config', 'core.hooksPath', path.join(root, '.hooks'));
  await copyHookSupportFiles(root, workspace, () => {});
  assert.equal(fs.existsSync(path.join(workspace, '.hooks', '_')), false, 'an absolute hooks path is shared by every worktree already');
});
