import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import express from 'express';
import { once } from 'node:events';

test('material versions, files, HTTP ownership, preparation marks and ready sources', async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'plangent-materials-'));
  process.env.PLANGENT_DATA_DIR = root;
  const { getDb } = await import('../../infrastructure/db/schema');
  const { createProject } = await import('../projects');
  const { createTask } = await import('../tasks');
  const { initQueues, getQueue, saveQueue } = await import('../orchestration/queue');
  const { createPlan, updatePlan } = await import('../orchestration/plans');
  const { createAnalysisSection } = await import('../orchestration/analysis');
  const { stopWatchAnalysis, getTaskDirectory, deleteTaskDirectory } = await import('../orchestration/task-files');
  const { onBroadcast } = await import('../shared/events');
  const materials = await import('./index');
  const stages = await import('./stages');
  const { materialsRouter, preparationRouter } = await import('../../infrastructure/http/routes/materials');
  initQueues();
  const project = createProject({ name: 'Materials', repo_path: root });
  const task = createTask({ project_id: project.id, key: 'MAT' });
  const events: string[] = [];
  const off = onBroadcast(event => events.push(event.type));
  const app = express();
  app.use('/projects/:projectId/tasks/:taskId/materials', materialsRouter);
  app.use('/projects/:projectId/tasks/:taskId/preparation', preparationRouter);
  const server = app.listen(0, '127.0.0.1');
  await once(server, 'listening');
  const base = `http://127.0.0.1:${(server.address() as { port: number }).port}/projects/${project.id}/tasks/${task.id}`;
  const request = (suffix: string, method = 'GET', body?: unknown) => fetch(base + suffix, {
    method, headers: { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body),
  });
  try {
    assert.equal(await (await request('/materials/qa')).json(), null);
    assert.equal((await fetch(base.replace(project.id, 'wrong') + '/materials/qa')).status, 404);
    assert.equal((await request('/materials/nope')).status, 400);
    assert.equal((await request('/materials/qa', 'PUT', { content: 4 })).status, 400);
    const response = await request('/materials/architecture', 'PUT', { content: '# **D1** Boundary', expected_version: 0, author: 'agent' });
    assert.equal(response.status, 200);
    const first = await response.json() as { version: number; author: string };
    assert.equal(first.version, 1);
    assert.equal(first.author, 'developer');
    assert.equal(fs.readFileSync(path.join(getTaskDirectory(root, task.key), 'architecture.md'), 'utf8'), '# **D1** Boundary');
    assert.equal((await request('/materials/architecture', 'PUT', { content: 'stale', expected_version: 0 })).status, 409);
    const second = materials.saveMaterial({ task_id: task.id, type: 'architecture', content: '**D2** Other', expected_version: 1, author: 'agent', session_id: 'session' });
    assert.equal(second.version, 2);
    assert.equal(second.session_id, 'session');
    assert.equal(materials.listMaterials(task.id, 'architecture')[1].content, '# **D1** Boundary');
    assert.deepEqual(materials.parseMaterialIdentifiers('# **D1** Boundary\n**Q3** Test\nText **Q4**\n```md\n**Q5** Example\n```\n**Q3** Again'), ['D1', 'Q3']);
    assert.deepEqual(stages.getReadyMaterials(task.id).analysis, []);
    createAnalysisSection({ task_id: task.id, title: 'Requirements', description: 'Goal' });
    stages.markPreparationStage(task.id, 'analysis', 'ready');
    const plan = createPlan({ task_id: task.id, content: '- [ ] (p1) Implement' });
    assert.equal((await request('/preparation/plan', 'POST', { status: 'ready' })).status, 200);
    assert.deepEqual(stages.getPreparationStages(task.id).map(item => item.status), ['ready', 'skipped', 'skipped', 'ready']);
    assert.equal(stages.getReadyMaterials(task.id).architecture, null);
    assert.ok(stages.getReadyMaterials(task.id).analysis.length);
    assert.equal((await request('/preparation/qa', 'POST', { status: 'ready' })).status, 400);
    stages.markPreparationStage(task.id, 'architecture', 'ready');
    materials.saveMaterial({ task_id: task.id, type: 'architecture', content: 'Changed' });
    assert.equal(stages.getPreparationStages(task.id)[1].status, 'ready');
    assert.equal(stages.getPreparationStages(task.id)[1].changed_since_mark, true);
    assert.equal(stages.getPreparationStages(task.id)[2].status, 'skipped');
    updatePlan(plan.id, '- [ ] (p1) Edited');
    assert.equal(stages.getPreparationStages(task.id)[3].changed_since_mark, true);
    assert.ok(events.includes('material_updated'));
    assert.ok(events.includes('stages_updated'));
    const queue = getQueue(task.id, project.id);
    queue.status = 'running';
    queue.stages = [{ id: 'stage', sessions: [{ id: 'session', status: 'running' }] }] as typeof queue.stages;
    saveQueue(queue);
    assert.equal((await request('/materials/qa', 'PUT', { content: 'Blocked' })).status, 409);
    assert.equal((await request('/preparation/qa', 'POST', { status: 'skipped' })).status, 409);
    getDb().prepare('DELETE FROM tasks WHERE id=?').run(task.id);
    assert.equal(getDb().prepare('SELECT * FROM materials WHERE task_id=?').all(task.id).length, 0);
    assert.equal(getDb().prepare('SELECT * FROM preparation_marks WHERE task_id=?').all(task.id).length, 0);
    deleteTaskDirectory(task, root);
    assert.equal(fs.existsSync(getTaskDirectory(root, task.key)), false);
  } finally {
    off(); stopWatchAnalysis(task.id);
    await new Promise<void>((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
    getDb().close();
    fs.rmSync(root, { recursive: true, force: true });
  }
});
