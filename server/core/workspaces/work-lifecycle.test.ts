import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import express from 'express';
import { once } from 'node:events';

test('work lifecycle, default viewing, recovery and notifications', async t => {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'plangent-work-lifecycle-'));
  process.env.PLANGENT_DATA_DIR = path.join(temporary, 'data');
  // Git mutations are confined to the disposable fixture, never the active project.
  const git = (cwd: string, ...args: string[]) => {
    assert.ok(!path.relative(temporary, cwd).startsWith('..'));
    return execFileSync('git', ['-c', 'core.autocrlf=false', ...args], { cwd, encoding: 'utf8', windowsHide: true, stdio: 'pipe' }).trim();
  };
  const { getDb } = await import('../../infrastructure/db/schema');
  const { createProject } = await import('../projects');
  const { createTask, getTask, updateTask, deleteTask } = await import('../tasks');
  const { initSessions, createSession, updateSession, addEvent } = await import('../agent-sessions/sessions');
  const { initQueues, getQueue, saveQueue } = await import('../orchestration/queue');
  const { createWorkspace, activeWorkspace, getWorkspace, rootForSession, WorkspaceRemovalError } = await import('.');
  const { closeWork, reopenWork, cancelErrand, addPlan } = await import('../work/actions');
  const { workEntry, workAttention } = await import('../work');
  const { initWorkEvents } = await import('../work/events');
  const { onBroadcast } = await import('../shared/events');
  const { sessionSignals } = await import('../agent-sessions/acp-host');
  const { recoverWorkspaces } = await import('./recovery');
  const { setViewing, viewing } = await import('./viewing');
  const { codeRouter } = await import('../../infrastructure/http/routes/code');
  const { createWorkspacesRouter } = await import('../../infrastructure/http/routes/workspaces');
  const db = getDb(); initSessions(); initQueues(); initWorkEvents();
  const repo = path.join(temporary, 'repo'), remote = path.join(temporary, 'remote.git');
  await fs.mkdir(repo); await fs.mkdir(remote);
  git(remote, 'init', '--bare', '-b', 'main'); git(repo, 'init', '-b', 'main');
  git(repo, 'config', 'user.name', 'Test'); git(repo, 'config', 'user.email', 'test@example.invalid');
  await fs.writeFile(path.join(repo, 'base.txt'), 'base\n'); git(repo, 'add', '.'); git(repo, 'commit', '-m', 'Fixture');
  git(repo, 'remote', 'add', 'origin', remote); git(repo, 'push', '-u', 'origin', 'main');
  const project = createProject({ name: 'Workflow', repo_path: repo });
  const task = createTask({ project_id: project.id, kind: 'errand' });
  const workspace = await createWorkspace(task.id, { branch: 'work/one', base: 'main' });
  updateTask(task.id, { branch_name: workspace.branch, base_branch: 'main' });
  const agent = db.prepare('SELECT id FROM agents LIMIT 1').get() as { id: string };
  const app = express(); app.use(express.json());
  app.use('/projects/:projectId/code', codeRouter);
  const otherTerminal = { id: 'shell-other', projectId: project.id, cwd: repo, workspaceId: null, title: 'dev', shell: 'sh', processes: [{ pid: 123, name: 'node' }] };
  app.use('/projects/:projectId/workspaces', createWorkspacesRouter(async () => [otherTerminal]));
  const server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = 'http://127.0.0.1:' + (server.address() as { port: number }).port + '/projects/' + project.id;
  const events: { type: string; [key: string]: unknown }[] = [];
  const stop = onBroadcast(event => events.push(event));
  try {
    await t.test('dirty close reports files, conversion keeps changes, reopen keeps branch and chat', async () => {
      await fs.writeFile(path.join(workspace.path, 'manual.txt'), 'Keep this');
      await assert.rejects(closeWork(task.id), error => error instanceof WorkspaceRemovalError && error.blockers.files.some(file => file.includes('manual.txt')));
      assert.equal(getTask(task.id)?.closed_at, null);
      await addPlan(task.id);
      assert.equal(getTask(task.id)?.kind, 'task');
      assert.equal(activeWorkspace(task.id)?.id, workspace.id);
      assert.equal(await fs.readFile(path.join(workspace.path, 'manual.txt'), 'utf8'), 'Keep this');
      git(workspace.path, 'add', 'manual.txt'); git(workspace.path, 'commit', '-m', 'Manual change');
      await assert.rejects(closeWork(task.id), error => error instanceof WorkspaceRemovalError && error.blockers.commits.length === 1);
      git(workspace.path, 'push', '-u', 'origin', workspace.branch);
      const chat = createSession({ project_id: project.id, task_id: task.id, role: 'task-chat', agent_id: agent.id, policy: 'ask', metadata: { workspace_id: workspace.id } });
      updateSession(chat.id, { status: 'complete' }); addEvent(chat.id, 'assistant', { text: 'Same chat' });
      await closeWork(task.id);
      assert.equal(activeWorkspace(task.id), null); assert.equal(getTask(task.id)?.status, 'done');
      assert.equal(git(repo, 'branch', '--show-current'), 'main');
      const { taskMrs } = await import('../task-mr');
      const mrs = taskMrs(), refresh = mrs.refresh;
      db.prepare('UPDATE tasks SET mr_link=? WHERE id=?').run('{"iid":1}', task.id);
      mrs.refresh = async () => ({ state: 'merged' } as never);
      try { await assert.rejects(reopenWork(task.id), /МР влит/); }
      finally { mrs.refresh = refresh; db.prepare('UPDATE tasks SET mr_link=NULL WHERE id=?').run(task.id); }
      await reopenWork(task.id);
      assert.equal(activeWorkspace(task.id)?.branch, workspace.branch);
      assert.equal(await fs.readFile(path.join(activeWorkspace(task.id)!.path, 'manual.txt'), 'utf8'), 'Keep this');
      assert.equal(await rootForSession({ ...chat, metadata: { workspace_id: workspace.id } }), activeWorkspace(task.id)?.path);
      assert.equal(workEntry(task.id).state.stage, 'check');
    });
    await t.test('view changes implicit HTTP root and reports running processes before confirmation', async () => {
      const current = activeWorkspace(task.id)!;
      await fs.writeFile(path.join(current.path, 'visible.txt'), 'Visible only here');
      assert.deepEqual(await (await fetch(base + '/code/changes')).json(), []);
      await fs.writeFile(path.join(repo, 'main-manual.txt'), 'Main edits stay here');
      const running = createSession({ project_id: project.id, task_id: task.id, role: 'executor', agent_id: agent.id, policy: 'ask' });
      updateSession(running.id, { status: 'thinking' });
      const response = await fetch(base + '/workspaces/viewing', { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ workspaceId: current.id }) });
      assert.equal(response.status, 409);
      const warnings = (await response.json() as { warnings: { agentWorking: boolean; terminals: typeof otherTerminal[] } }).warnings;
      assert.equal(warnings.agentWorking, true);
      assert.deepEqual(warnings.terminals[0].processes, otherTerminal.processes);
      assert.equal(viewing(project.id), null);
      const confirmed = await fetch(base + '/workspaces/viewing', { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ workspaceId: current.id, confirmed: true }) });
      assert.equal(confirmed.status, 200);
      assert.ok((await (await fetch(base + '/code/changes')).json() as { path: string }[]).some(file => file.path === 'visible.txt'));
      assert.equal(git(repo, 'branch', '--show-current'), 'main');
      setViewing(project.id, null);
      assert.equal(await fs.readFile(path.join(repo, 'main-manual.txt'), 'utf8'), 'Main edits stay here');
      assert.ok((await (await fetch(base + '/code/changes')).json() as { path: string }[]).some(file => file.path === 'main-manual.txt'));
      updateSession(running.id, { status: 'complete' });
      assert.equal(workAttention().find(entry => entry.projectId === project.id)?.count, 1);
    });
    await t.test('lost folders and interrupted preparation become recoverable failures', async () => {
      const current = activeWorkspace(task.id)!;
      setViewing(project.id, current.id);
      assert.ok(!path.relative(temporary, current.path).startsWith('..'));
      await fs.rm(current.path, { recursive: true, force: true });
      await recoverWorkspaces();
      assert.equal(getWorkspace(current.id).status, 'failed');
      assert.match(getWorkspace(current.id).error, /Пересоздайте/);
      assert.equal(workEntry(task.id).state.action, 'recreate');
      assert.equal(viewing(project.id), null);
      const recreated = await fetch(base + '/workspaces/' + current.id + '/recreate', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' });
      assert.equal(recreated.status, 200);
      assert.equal(activeWorkspace(task.id)?.branch, current.branch);
      const { insertWorkspace } = await import('./store');
      const preparingTask = createTask({ project_id: project.id });
      const preparing = insertWorkspace({ project_id: project.id, task_id: preparingTask.id, branch: 'preparing', base_branch: 'main', path: path.join(temporary, 'missing') });
      await recoverWorkspaces();
      assert.equal(getWorkspace(preparing.id).status, 'failed');
      assert.match(getWorkspace(preparing.id).error, /прервана/);
    });
    await t.test('turns and queue completion notify once, fixes are identified separately', async () => {
      const errand = createTask({ project_id: project.id, kind: 'errand' });
      const session = createSession({ project_id: project.id, task_id: errand.id, agent_id: agent.id, role: 'errand', policy: 'ask' });
      updateSession(session.id, { status: 'ready' }); addEvent(session.id, 'user', { text: 'Do it' });
      addEvent(session.id, 'turn_end', { stopReason: 'end_turn' });
      sessionSignals.emit('turn_end', session.id); sessionSignals.emit('turn_end', session.id);
      const ready = events.filter(e => e.type === 'work:ready_for_check' && e.taskId === errand.id);
      assert.equal(ready.length, 1); assert.equal(ready[0].taskKey, errand.key); assert.equal(ready[0].projectId, project.id);
      updateSession(session.id, { status: 'ready', metadata: { work_fix_pending: true } });
      addEvent(session.id, 'turn_end', { stopReason: 'end_turn' }); sessionSignals.emit('turn_end', session.id);
      assert.equal(events.filter(e => e.type === 'work:fixes_ready' && e.taskId === errand.id).length, 1);
      const queue = getQueue(errand.id, project.id); queue.status = 'running'; saveQueue(queue);
      queue.status = 'finished'; saveQueue(queue); saveQueue(queue);
      assert.equal(events.filter(e => e.type === 'work:ready_for_check' && e.taskId === errand.id).length, 2);
      await cancelErrand(errand.id, 'keep');
      assert.equal(getTask(errand.id)?.close_reason, 'cancelled');
      const retained = createTask({ project_id: project.id, kind: 'errand' });
      const retainedWorkspace = await createWorkspace(retained.id, { branch: 'work/retained', base: 'main' });
      await fs.writeFile(path.join(retainedWorkspace.path, 'keep.txt'), 'Manual edits');
      await cancelErrand(retained.id, 'keep');
      assert.equal(activeWorkspace(retained.id)?.id, retainedWorkspace.id);
      assert.equal(await fs.readFile(path.join(retainedWorkspace.path, 'keep.txt'), 'utf8'), 'Manual edits');
      await assert.rejects(deleteTask(retained.id), error => error instanceof WorkspaceRemovalError);
      assert.ok(getTask(retained.id));
      await reopenWork(retained.id);
      await cancelErrand(retained.id, 'discard');
      assert.equal(activeWorkspace(retained.id), null);
      assert.ok(!git(repo, 'branch', '--list', 'work/retained'));
      const plain = createTask({ project_id: project.id }); await closeWork(plain.id);
      assert.equal(getTask(plain.id)?.status, 'done'); await deleteTask(plain.id); assert.equal(getTask(plain.id), null);
    });
  } finally {
    stop(); await new Promise<void>(resolve => server.close(() => resolve())); db.close();
    assert.ok(path.resolve(temporary).startsWith(path.resolve(os.tmpdir()) + path.sep));
    await fs.rm(temporary, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 });
  }
});
