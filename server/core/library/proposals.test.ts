import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

test('library proposals apply, detach, reject and detect stale snapshots without changing other projects', async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'plangent-proposals-'));
  const cwd = process.cwd();
  process.chdir(root);
  process.env.PLANGENT_DATA_DIR = path.join(root, 'data');
  const { getDb } = await import('../../infrastructure/db/schema');
  const { createProject } = await import('../projects');
  const sessions = await import('../agent-sessions/sessions');
  const library = await import('./index');
  const files = await import('./library-manager');
  const proposals = await import('./proposals');
  sessions.initSessions();
  try {
    const group = createProject({ name: 'Group', kind: 'group' });
    const project = createProject({ name: 'Project', repo_path: path.join(root, 'project'), group_id: group.id });
    const sibling = createProject({ name: 'Sibling', repo_path: path.join(root, 'sibling'), group_id: group.id });
    const session = sessions.createSession({ project_id: project.id, agent_id: 'agent-claude', role: 'librarian', policy: 'allow-all' });
    assert.equal(session.policy, 'read-only');
    assert.throws(() => sessions.updateSession(session.id, { policy: 'allow-all' }), /read-only/);
    const input = { action: 'create' as const, type: 'skill' as const, slug: 'testing-store', title: 'Store tests', content: 'Use project examples.', explanation: 'Needed for store tests' };
    const pending = proposals.proposeLibraryChange(session.id, input);
    assert.equal(library.listLibraryItems().length, 0);
    assert.equal(pending.status, 'pending');
    const item = proposals.applyProposal(pending.id);
    assert.equal(item.content, input.content);
    assert.deepEqual(item.targets, [project.id]);
    assert.equal(files.readItemContent(item), input.content);
    assert.equal(proposals.getProposal(pending.id).status, 'applied');
    assert.throws(() => proposals.applyProposal(pending.id), /applied/);
    assert.ok(fs.existsSync(path.join(project.repo_path, '.claude', 'skills', 'plangent-testing-store', 'SKILL.md')));
    const update = { ...input, action: 'update' as const, item_id: item.id, content: 'Improved tests.' };
    const change = proposals.proposeLibraryChange(session.id, update);
    assert.equal(change.snapshot?.content, input.content);
    assert.equal(proposals.applyProposal(change.id).id, item.id);
    const stale = proposals.proposeLibraryChange(session.id, update);
    files.writeItemContent(item, 'Developer changes');
    assert.throws(() => proposals.applyProposal(stale.id), /stale/);
    assert.equal(proposals.getProposal(stale.id).status, 'stale');
    assert.equal(files.readItemContent(item), 'Developer changes');
    const metadataStale = proposals.proposeLibraryChange(session.id, update);
    library.updateLibraryItem(item.id, { title: 'New title' });
    assert.throws(() => proposals.applyProposal(metadataStale.id), /stale/);
    const rejected = proposals.proposeLibraryChange(session.id, { ...input, slug: 'rejected-skill' });
    proposals.rejectProposal(rejected.id);
    assert.throws(() => proposals.applyProposal(rejected.id), /rejected/);
    assert.equal(library.listLibraryItems().length, 1);
    const shared = library.createLibraryItem({ type: 'skill', slug: 'shared-skill', title: 'Shared', scope: 'project', targets: [group.id] });
    files.writeItemContent(shared, 'Shared original');
    const detached = proposals.proposeLibraryChange(session.id, { ...update, item_id: shared.id, slug: shared.slug, content: 'Project copy' });
    const copy = proposals.applyProposal(detached.id);
    assert.equal(copy.detached_from, shared.id);
    assert.deepEqual(copy.targets, [project.id]);
    assert.equal(files.readItemContent(library.getLibraryItem(shared.id)!), 'Shared original');
    assert.ok(library.getLibraryItem(shared.id)!.excluded.includes(project.id));
    assert.ok(library.libraryItemsFor(sibling).some(i => i.id === shared.id));
    assert.ok(!library.libraryItemsFor(project).some(i => i.id === shared.id));
    assert.ok(fs.existsSync(path.join(project.repo_path, '.claude', 'skills', 'plangent-shared-skill', 'SKILL.md')));
    assert.throws(() => proposals.proposeLibraryChange(session.id, { ...input, slug: '../escape' }), /slug/);
    assert.throws(() => proposals.proposeLibraryChange(session.id, { ...input, type: 'instruction-guide' as 'skill' }), /type/);
    assert.throws(() => proposals.proposeLibraryChange(session.id, { ...input, targets: ['missing'] }), /targets/);
    const main = library.createLibraryItem({ type: 'main', slug: 'main', title: 'Main', scope: 'project', targets: [project.id] });
    const conflictingMain = proposals.proposeLibraryChange(session.id, { ...input, type: 'main', slug: 'another-main' });
    assert.throws(() => proposals.applyProposal(conflictingMain.id), /main file/);
    assert.equal(proposals.getProposal(conflictingMain.id).status, 'pending');
    const separate = proposals.proposeLibraryChange(session.id, { ...input, slug: 'sibling-only' });
    const applied = proposals.applyProposal(separate.id, { scope: 'project', targets: [sibling.id] });
    assert.deepEqual(applied.targets, [sibling.id]);
    assert.ok(library.getLibraryItem(main.id));
    assert.equal(proposals.listProposals({ sessionId: session.id }).length, proposals.listProposals({ projectId: project.id }).length);
    const survivesChat = proposals.proposeLibraryChange(session.id, { ...input, slug: 'survives-chat' });
    sessions.deleteSession(session.id);
    assert.equal(proposals.getProposal(survivesChat.id).status, 'pending');
    assert.equal(proposals.applyProposal(survivesChat.id).slug, 'survives-chat');
  } finally {
    getDb().close();
    process.chdir(cwd);
    fs.rmSync(root, { recursive: true, force: true });
  }
});
