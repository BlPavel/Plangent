// Extracts only the vscode-icons (MIT) icons referenced in file-icons.ts into icon-set.ts.
// Run: node scripts/gen-file-icons.cjs (needs the @iconify-json/vscode-icons dev dependency).
const fs = require('fs'), path = require('path')
const dir = path.join(__dirname, '..', 'client', 'src', 'shared', 'code-viewer')
const source = fs.readFileSync(path.join(dir, 'file-icons.ts'), 'utf8')
const names = new Set(['default-file', 'default-folder', 'default-folder-opened'])
for (const [, name] of source.matchAll(/'((?:file-type|folder-type|default)-[a-z0-9-]+)'/g)) {
  names.add(name)
  if (name.startsWith('folder-type-')) names.add(name + '-opened')
}
const set = require('@iconify-json/vscode-icons/icons.json')
const icons = {}
for (const name of [...names].sort()) {
  const icon = set.icons[name]
  if (!icon) throw new Error('Missing icon: ' + name)
  icons[name] = icon.body
}
const out = `// Generated by scripts/gen-file-icons.cjs from @iconify-json/vscode-icons (MIT, https://github.com/vscode-icons/vscode-icons). Do not edit.
export const ICON_SET: { size: number; icons: Record<string, string> } = ${JSON.stringify({ size: set.height ?? 32, icons }, null, 2)}
`
fs.writeFileSync(path.join(dir, 'icon-set.ts'), out)
console.log('icons:', Object.keys(icons).length)
